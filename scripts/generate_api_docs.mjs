#!/usr/bin/env node
/**
 * Writes docs/API.md and docs/API_zh.md from the doc comments in
 * minigame/minigame.lua. Run it after changing the Lua module:
 *
 *   node scripts/generate_api_docs.mjs          write both files
 *   node scripts/generate_api_docs.mjs --check  fail if either file is stale
 */

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import { REPO_ROOT } from "../src/util.mjs";
import { readLuaApi } from "./lib/lua_api.mjs";

const PAYMENT = "| WeChat | `wx.requestMidasPayment` |\n| Douyin | `tt.requestGamePayment` |\n| TikTok | `TTMinis.game.pay` |";

export function renderApi(language) {
  const api = readLuaApi();
  const zh = JSON.parse(readFileSync(join(REPO_ROOT, "scripts", "lib", "api_zh.json"), "utf8"));
  const chinese = language === "zh";
  const describe = (table, record) => (chinese ? table[record.name] : record.description);
  const out = [];

  out.push(chinese ? "# Lua SDK 参考" : "# Lua SDK reference", "");
  out.push(chinese
    ? "<!-- 本文件由 scripts/generate_api_docs.mjs 根据 minigame/minigame.lua 的注释生成，不要手工修改。 -->"
    : "<!-- Generated by scripts/generate_api_docs.mjs from the comments in minigame/minigame.lua. Do not edit. -->", "");
  out.push(chinese
    ? `\`minigame\` 模块共有 ${api.count} 个函数。回调约定：第一个参数是结果（失败时为 nil），最后一个参数是错误信息（成功时为 nil）。不在小游戏里时，取值函数返回默认值，回调立即收到 \`"not running in a mini game"\`。`
    : `The \`minigame\` module has ${api.count} functions. Callback convention: the first argument is the result (nil on failure) and the last one is an error string (nil on success). Outside a mini game, getters return defaults and callbacks receive \`"not running in a mini game"\` immediately.`, "");
  out.push("```lua", 'local minigame = require "minigame.minigame"', "```", "");
  out.push(chinese
    ? "这里列出的是模块提供的函数，不代表每个宿主都支持其中的每一个。封装函数底层调用同名的宿主接口，宿主没有实现时，回调会收到“is not supported”的错误。"
    : "This is the surface of the module, not a promise that every host implements all of it. A wrapper calls the host API of the same name; where the host has none, the callback receives an \"is not supported\" error.", "");

  for (const group of api.groups) {
    out.push(`## ${chinese ? (zh.groups[group.title] || group.title) : group.title}`, "");
    for (const record of group.functions) {
      out.push(`### \`${record.signature}\``, "", describe(zh.functions, record), "");
      if (!chinese && record.tags.length > 0) {
        for (const tag of record.tags) out.push(`- \`${tag.split(" ")[0]}\` ${tag.split(" ").slice(1).join(" ")}`);
        out.push("");
      }
      if (record.name === "request_payment") {
        out.push(chinese ? "| 平台 | 实际调用的宿主接口 |" : "| Platform | Host API that is called |", "|---|---|", PAYMENT, "");
      }
    }
  }

  out.push(chinese ? "## 宿主对象" : "## Host objects", "");
  out.push(chinese
    ? "`minigame.create()` 返回的对象，以及广告、音频封装内部的 `object` 字段，都有这些方法。"
    : "Objects returned by `minigame.create()`, and the `object` field inside the ad and audio wrappers, have these methods.", "");
  for (const record of api.methods) {
    out.push(`### \`${record.signature}\``, "", describe(zh.methods, record), "");
  }
  return `${out.join("\n").trimEnd()}\n`;
}

const targets = [["en", "API.md"], ["zh", "API_zh.md"]];

if (process.argv[1] && process.argv[1].endsWith("generate_api_docs.mjs")) {
  const check = process.argv.includes("--check");
  let stale = false;
  for (const [language, file] of targets) {
    const path = join(REPO_ROOT, "docs", file);
    const text = renderApi(language);
    if (check) {
      if (!existsSync(path) || readFileSync(path, "utf8") !== text) {
        console.error(`docs/${file} is out of date; run node scripts/generate_api_docs.mjs`);
        stale = true;
      }
    } else {
      writeFileSync(path, text);
      console.log(`wrote docs/${file}`);
    }
  }
  if (stale) process.exitCode = 1;
}
