#!/usr/bin/env node
/**
 * Writes the reference files of the agent skill in skills/defold-minigame/
 * from the English documents. The skill then carries the manuals with it,
 * also where it was installed without the rest of the repository, and cannot
 * say something the documents do not. Run it after changing a document:
 *
 *   node scripts/generate_skill_references.mjs          write the files
 *   node scripts/generate_skill_references.mjs --check  fail if a file is stale
 */

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, dirname, join, posix } from "node:path";
import { fileURLToPath } from "node:url";

import { REPO_ROOT } from "../src/util.mjs";

export const SKILL_DIR = "skills/defold-minigame";

/** The documents the skill carries, and the name each one has inside it. */
export const REFERENCES = [
  { source: "docs/QUICK_START.md", target: "references/quick-start.md" },
  { source: "docs/USAGE.md", target: "references/usage.md" },
  { source: "docs/API.md", target: "references/api.md" },
];

const repository = () => JSON.parse(readFileSync(join(REPO_ROOT, "package.json"), "utf8")).repository.url.replace(/\.git$/, "");

/**
 * The address a link of a document has inside the skill: another reference
 * file when the skill carries the target, the file in the repository
 * otherwise. Addresses that already leave the document are kept.
 */
function rewriteLink(target, source) {
  if (/^(?:[a-z][a-z0-9+.-]*:|#)/i.test(target)) return target;
  const [path, anchor] = target.split("#");
  const file = posix.normalize(posix.join(posix.dirname(source), path));
  const carried = REFERENCES.find((reference) => reference.source === file);
  const suffix = anchor ? `#${anchor}` : "";
  if (carried) return `${basename(carried.target)}${suffix}`;
  if (!existsSync(join(REPO_ROOT, file))) throw new Error(`${source} links to ${target}, which is not in the repository`);
  return `${repository()}/blob/main/${file}${suffix}`;
}

export function renderReference(reference) {
  const text = readFileSync(join(REPO_ROOT, reference.source), "utf8");
  const lines = text.split("\n").filter((line) => !/^<!-- Generated by .* -->$/.test(line));
  const body = lines.join("\n")
    // A figure cannot be shown where the skill is read; what it shows is in its description.
    .replace(/!\[([^\]]*)\]\([^)]*\)/g, (_, description) => `*Figure: ${description}.*`)
    .replace(/\]\(([^)\s]+)\)/g, (_, target) => `](${rewriteLink(target, reference.source)})`);
  const title = body.indexOf("\n");
  const note = `<!-- Generated by scripts/generate_skill_references.mjs from ${reference.source}. Do not edit. -->`;
  return `${body.slice(0, title)}\n\n${note}\n${body.slice(title + 1).replace(/^\n+/, "\n")}`;
}

function main(argv) {
  const check = argv.includes("--check");
  let stale = 0;
  for (const reference of REFERENCES) {
    const file = join(REPO_ROOT, SKILL_DIR, reference.target);
    const rendered = renderReference(reference);
    if (check) {
      if (!existsSync(file) || readFileSync(file, "utf8") !== rendered) {
        process.stderr.write(`${SKILL_DIR}/${reference.target} is stale; run node scripts/generate_skill_references.mjs\n`);
        stale += 1;
      }
      continue;
    }
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, rendered);
    process.stdout.write(`wrote ${SKILL_DIR}/${reference.target}\n`);
  }
  return stale === 0 ? 0 : 1;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) process.exitCode = main(process.argv.slice(2));
